-- 045: 게시글 좋아요·스크랩·신고를 post_reactions 하나로 통합 (Issue #159)
--
-- post_likes, post_scraps, post_reports는 모두 "회원 × 게시글" 관계라 reaction_type으로 구분한다.
--   LIKE   : 좋아요 (회원·게시글당 1회)
--   SCRAP  : 스크랩 (회원·게시글당 1회)
--   REPORT : 신고   (회원·게시글당 1회, reason 필수·details 선택)
-- 기존 신고 번호(report_id)는 reaction_id로 그대로 옮긴다(관리자 화면에서 신고 식별에 사용).
-- 좋아요·스크랩·신고의 created_at과 외래키(posts·members, 삭제 규칙 없음)는 기존과 같다.
--
-- 전제: 044 적용. 백업 후 실행. 한 트랜잭션, 재실행 가능(옮긴 뒤에는 아무것도 하지 않음).
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '120s';
SET LOCAL search_path = public, pg_catalog;

CREATE TABLE IF NOT EXISTS post_reactions (
    reaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    post_id BIGINT NOT NULL REFERENCES posts(post_id),
    member_id BIGINT NOT NULL REFERENCES members(member_id),
    reaction_type VARCHAR(10) NOT NULL
        CHECK (reaction_type IN ('LIKE', 'SCRAP', 'REPORT')),
    reason VARCHAR(20)
        CHECK (reason IN ('SPAM', 'ABUSE', 'HATE', 'PRIVACY', 'OTHER')),
    details VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_post_reactions PRIMARY KEY (post_id, reaction_type, member_id),
    CONSTRAINT uq_post_reactions_id UNIQUE (reaction_id),
    -- 신고만 사유가 있고, 상세 내용도 신고에만 쓴다.
    CONSTRAINT ck_post_reactions_report_fields CHECK (
        (reaction_type = 'REPORT') = (reason IS NOT NULL)
        AND (reaction_type = 'REPORT' OR details IS NULL)
    )
);

-- 마이페이지 좋아요·스크랩 목록, 회원 탈퇴 정리
CREATE INDEX IF NOT EXISTS idx_post_reactions_member
    ON post_reactions (member_id, reaction_type, created_at DESC);
-- HOT·명예의 전당: 좋아요만 모아 집계. 통합 테이블 전체를 읽지 않고 이 인덱스만 읽는다
-- (대량 데이터 측정: 예전 post_likes 순차 읽기보다 약 15% 빠름).
CREATE INDEX IF NOT EXISTS idx_post_reactions_likes
    ON post_reactions (post_id, created_at)
    WHERE reaction_type = 'LIKE';
-- 관리자 신고 목록·상세: 신고 행만 인덱스에서 읽는다(게시글별·최근순).
CREATE INDEX IF NOT EXISTS idx_post_reactions_reports
    ON post_reactions (post_id, created_at)
    INCLUDE (reaction_id, member_id)
    WHERE reaction_type = 'REPORT';
-- 044·045 개발 중 잠시 쓰던 신고 시각 인덱스(위 인덱스로 대체)
DROP INDEX IF EXISTS idx_post_reactions_reports_created;

DO $$
DECLARE
    expected_like BIGINT := 0;
    expected_scrap BIGINT := 0;
    expected_report BIGINT := 0;
BEGIN
    -- 신고 먼저: 기존 report_id를 reaction_id로 보존하고, 이후 번호가 겹치지 않게 시퀀스를 올린다.
    IF to_regclass('public.post_reports') IS NOT NULL THEN
        SELECT COUNT(*) INTO expected_report FROM post_reports;
        INSERT INTO post_reactions (reaction_id, post_id, member_id, reaction_type, reason, details, created_at)
        SELECT report_id, post_id, reporter_member_id, 'REPORT', reason, details, created_at
        FROM post_reports;
        PERFORM setval(
            pg_get_serial_sequence('public.post_reactions', 'reaction_id'),
            GREATEST((SELECT COALESCE(MAX(reaction_id), 0) FROM post_reactions), 1)
        );
        IF (SELECT COUNT(*) FROM post_reactions WHERE reaction_type = 'REPORT') <> expected_report THEN
            RAISE EXCEPTION '신고 이관 건수 불일치';
        END IF;
        DROP TABLE post_reports;
    END IF;

    IF to_regclass('public.post_likes') IS NOT NULL THEN
        SELECT COUNT(*) INTO expected_like FROM post_likes;
        INSERT INTO post_reactions (post_id, member_id, reaction_type, created_at)
        SELECT post_id, member_id, 'LIKE', created_at FROM post_likes
        ORDER BY created_at, post_id, member_id;
        IF (SELECT COUNT(*) FROM post_reactions WHERE reaction_type = 'LIKE') <> expected_like THEN
            RAISE EXCEPTION '좋아요 이관 건수 불일치';
        END IF;
        DROP TABLE post_likes;
    END IF;

    IF to_regclass('public.post_scraps') IS NOT NULL THEN
        SELECT COUNT(*) INTO expected_scrap FROM post_scraps;
        INSERT INTO post_reactions (post_id, member_id, reaction_type, created_at)
        SELECT post_id, member_id, 'SCRAP', created_at FROM post_scraps
        ORDER BY created_at, post_id, member_id;
        IF (SELECT COUNT(*) FROM post_reactions WHERE reaction_type = 'SCRAP') <> expected_scrap THEN
            RAISE EXCEPTION '스크랩 이관 건수 불일치';
        END IF;
        DROP TABLE post_scraps;
    END IF;
END $$;

COMMIT;

