-- PLAYMATE 커리어 연구소
-- STEP 15-1. DB 테이블 생성
-- =========================================================

BEGIN;

-- 1. 커리어 연구소 게시글 상세 정보
CREATE TABLE IF NOT EXISTS career_labs (
    post_id BIGINT PRIMARY KEY
        REFERENCES career_posts(post_id)
        ON DELETE CASCADE,

    -- 게시글 유형: 질문 / 토론
    post_type VARCHAR(20) NOT NULL
        CHECK (post_type IN ('QUESTION', 'DISCUSSION')),

    -- 질문 해결 여부
    is_resolved BOOLEAN NOT NULL DEFAULT FALSE,

    -- 질문형 게시글에서만 해결 상태 사용
    CONSTRAINT ck_career_labs_resolved
        CHECK (
            post_type = 'QUESTION'
            OR is_resolved = FALSE
        )
);


-- 2. 토론 투표 선택지
CREATE TABLE IF NOT EXISTS career_lab_poll_options (
    option_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    post_id BIGINT NOT NULL
        REFERENCES career_labs(post_id)
        ON DELETE CASCADE,

    option_text VARCHAR(200) NOT NULL,

    display_order SMALLINT NOT NULL
        CHECK (display_order BETWEEN 1 AND 10),

    CONSTRAINT uq_career_lab_poll_order
        UNIQUE (post_id, display_order),

    CONSTRAINT uq_career_lab_poll_option_post
        UNIQUE (post_id, option_id),

    CONSTRAINT ck_career_lab_poll_text
        CHECK (BTRIM(option_text) <> '')
);


-- 3. 회원별 투표 기록
CREATE TABLE IF NOT EXISTS career_lab_poll_votes (
    post_id BIGINT NOT NULL,

    member_id BIGINT NOT NULL
        REFERENCES members(member_id),

    option_id BIGINT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- 한 회원은 같은 게시글에 한 번만 투표
    PRIMARY KEY (post_id, member_id),

    -- 다른 게시글의 선택지에 투표하는 것 방지
    CONSTRAINT fk_career_lab_vote_option
        FOREIGN KEY (post_id, option_id)
        REFERENCES career_lab_poll_options(post_id, option_id)
        ON DELETE CASCADE
);


-- 4. 조회 인덱스
CREATE INDEX IF NOT EXISTS idx_career_labs_type
    ON career_labs (post_type);

CREATE INDEX IF NOT EXISTS idx_career_labs_resolved
    ON career_labs (is_resolved);

CREATE INDEX IF NOT EXISTS idx_career_lab_votes_option
    ON career_lab_poll_votes (option_id);

COMMIT;
