    class BackendUpdate:
        """A second connection playing the backend: UPDATE recruits SET recruit_mode='short'."""

        def __init__(self, recruit_id):
            self.recruit_id = recruit_id
            self.conn = psycopg.connect(DSN, options=db_options)  # explicit transaction
            self.task = None
            self.blocked = None

        def start(self):
            self.task = asyncio.create_task(asyncio.to_thread(
                self.conn.execute, "UPDATE recruits SET recruit_mode='short' WHERE recruit_id=%s",
                (self.recruit_id,)))

        async def probe(self, seconds=0.7):
            await asyncio.sleep(seconds)
            self.blocked = not self.task.done()

        async def finish(self):
            await self.task
            self.conn.commit()
            self.conn.close()

    def mode_of(recruit_id):
        return conn.execute("SELECT recruit_mode FROM recruits WHERE recruit_id=%s", (recruit_id,)).fetchone()[0]

    def writes_of(*channels):
        return sum(getattr(c, "perm_writes", 0) for c in channels)

    def flip_after_snapshot(repository, recruit_id):
        """The participant snapshot is read, THEN the mode becomes short (committed)."""
        real = repository.list_participant_states

        def snapshot():
            states = real()
            to_short(recruit_id)()
            return states

        repository.list_participant_states = snapshot
        return lambda: setattr(repository, "list_participant_states", real)

