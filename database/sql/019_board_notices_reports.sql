-- PLAYMATE 3·4단계: 과정 게시판 자동 공지 + 게시글 신고
-- 전제: 018_course_cohort_boards.sql 적용 완료, 공지사항 게시판/ADMIN 회원 존재
-- 백업 후 실행. 트랜잭션 단위, 재실행 가능.
BEGIN;

CREATE TABLE IF NOT EXISTS board_notice_posts (
    board_id BIGINT PRIMARY KEY REFERENCES boards(board_id),
    post_id BIGINT NOT NULL UNIQUE REFERENCES posts(post_id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS post_reports (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL REFERENCES posts(post_id),
    reporter_member_id BIGINT NOT NULL REFERENCES members(member_id),
    reason VARCHAR(20) NOT NULL CHECK (reason IN ('SPAM', 'ABUSE', 'HATE', 'PRIVACY', 'OTHER')),
    details VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_post_reporter UNIQUE (post_id, reporter_member_id)
);
CREATE INDEX IF NOT EXISTS idx_post_reports_created ON post_reports (created_at DESC);

-- 이미 만들어진 과정·기수 게시판의 설명을 공지사항에 한 건씩 등록.
-- INSERT 공지와 대응표 INSERT가 동일 트랜잭션에서 실행됩니다.
DO $$
DECLARE
    notice_board BIGINT;
    admin_member BIGINT;
    course_board RECORD;
    new_post BIGINT;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM boards WHERE course_code IS NOT NULL AND cohort IS NOT NULL) THEN
        RETURN;
    END IF;

    SELECT board_id INTO notice_board FROM boards WHERE board_name = '공지사항' LIMIT 1;
    SELECT member_id INTO admin_member FROM members
    WHERE UPPER(BTRIM(COALESCE(role_code, ''))) = 'ADMIN'
    ORDER BY member_id LIMIT 1;
    IF notice_board IS NULL OR admin_member IS NULL THEN
        RAISE EXCEPTION '공지사항 게시판과 ADMIN 회원이 있어야 자동 공지를 생성할 수 있습니다.';
    END IF;

    FOR course_board IN
        SELECT b.board_id, b.board_name, b.description
        FROM boards b
        LEFT JOIN board_notice_posts bn ON bn.board_id = b.board_id
        WHERE b.course_code IS NOT NULL AND b.cohort IS NOT NULL
          AND bn.board_id IS NULL
        ORDER BY b.board_id
    LOOP
        INSERT INTO posts (
            board_id, author_member_id, post_type, title, body,
            source_type, post_status, published_at, is_anonymous
        ) VALUES (
            notice_board, admin_member, 'BOARD',
            '[게시판 안내] ' || course_board.board_name,
            course_board.board_name || E' 게시판이 개설되었습니다.\n\n' ||
                COALESCE(course_board.description, '') || E'\n\n' ||
                '열람은 모든 회원에게 열려 있으며 글과 댓글은 해당 과정·기수 회원만 작성할 수 있습니다.',
            'SYSTEM', 'PUBLISHED', CURRENT_TIMESTAMP, FALSE
        ) RETURNING post_id INTO new_post;

        INSERT INTO board_notice_posts (board_id, post_id)
        VALUES (course_board.board_id, new_post);
    END LOOP;
END $$;
COMMIT;

-- 확인 (SQL 편집기에서 별도로 실행 가능)
SELECT b.board_name, bn.post_id AS notice_post_id
FROM boards b
LEFT JOIN board_notice_posts bn ON bn.board_id = b.board_id
WHERE b.course_code IS NOT NULL AND b.cohort IS NOT NULL
ORDER BY b.board_id;
