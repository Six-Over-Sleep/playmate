-- PlayMate 035: 마이페이지 업적/대표 배지 + 웹 알림 + 알림 설정
-- PostgreSQL 18 / prerequisites: 033(game_badges, game_member_badges), 034(dm_messages)
-- 기존 notifications는 Discord Bot 전송 큐이므로 변경하지 않는다.
BEGIN;

-- GameZone 이외의 커뮤니티/학습/활동 업적 정의. 게임 배지는 033 테이블을 재사용한다.
CREATE TABLE IF NOT EXISTS public.achievement_definitions (
    achievement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    achievement_code VARCHAR(64) NOT NULL UNIQUE,
    achievement_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    category VARCHAR(24) NOT NULL,
    rarity VARCHAR(16) NOT NULL DEFAULT 'COMMON',
    icon_key VARCHAR(100),
    award_rule JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_achievement_category CHECK (category IN ('COMMUNITY', 'SKILL', 'SOCIAL', 'EVENT')),
    CONSTRAINT chk_achievement_rarity CHECK (rarity IN ('COMMON', 'RARE', 'EPIC', 'LEGENDARY')),
    CONSTRAINT chk_achievement_rule_json CHECK (jsonb_typeof(award_rule) = 'object')
);

CREATE TABLE IF NOT EXISTS public.member_achievements (
    member_id BIGINT NOT NULL REFERENCES public.members(member_id) ON DELETE CASCADE,
    achievement_id BIGINT NOT NULL REFERENCES public.achievement_definitions(achievement_id),
    award_event_key VARCHAR(160) NOT NULL,
    awarded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    award_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (member_id, achievement_id),
    CONSTRAINT uq_member_achievements_event UNIQUE (member_id, award_event_key),
    CONSTRAINT chk_member_achievements_metadata CHECK (jsonb_typeof(award_metadata) = 'object')
);
CREATE INDEX IF NOT EXISTS idx_member_achievements_recent
    ON public.member_achievements(member_id, awarded_at DESC);

-- 대표 배지 1개: 커뮤니티 업적 또는 기존 GameZone 배지 중 선택. 반드시 본인 획득 기록이어야 한다.
CREATE TABLE IF NOT EXISTS public.member_profile_preferences (
    member_id BIGINT PRIMARY KEY REFERENCES public.members(member_id) ON DELETE CASCADE,
    featured_achievement_id BIGINT,
    featured_game_badge_id BIGINT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_member_profile_one_badge CHECK (
        NUM_NONNULLS(featured_achievement_id, featured_game_badge_id) <= 1
    ),
    CONSTRAINT fk_member_profile_owned_achievement
        FOREIGN KEY (member_id, featured_achievement_id)
        REFERENCES public.member_achievements(member_id, achievement_id)
        ON DELETE SET NULL (featured_achievement_id),
    CONSTRAINT fk_member_profile_owned_game_badge
        FOREIGN KEY (member_id, featured_game_badge_id)
        REFERENCES public.game_member_badges(member_id, badge_id)
        ON DELETE SET NULL (featured_game_badge_id)
);

-- 이벤트 유형별 알림 수신 설정: 행이 없으면 수신 ON으로 취급.
-- SYSTEM은 보안/계정 고지에 사용할 수 있으므로 비활성화 불가.
CREATE TABLE IF NOT EXISTS public.notification_preferences (
    member_id BIGINT NOT NULL REFERENCES public.members(member_id) ON DELETE CASCADE,
    notification_type VARCHAR(24) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (member_id, notification_type),
    CONSTRAINT chk_notification_preferences_type CHECK (
        notification_type IN ('COMMENT', 'REPLY', 'REACTION', 'DM_MESSAGE', 'ACHIEVEMENT', 'SYSTEM')
    ),
    CONSTRAINT chk_notification_preferences_system CHECK (
        notification_type <> 'SYSTEM' OR enabled
    )
);

-- 웹 내부 알림. 기존 notifications(Discord Bot 큐)와 물리적으로 분리.
CREATE TABLE IF NOT EXISTS public.user_notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_member_id BIGINT NOT NULL REFERENCES public.members(member_id) ON DELETE CASCADE,
    actor_member_id BIGINT REFERENCES public.members(member_id) ON DELETE SET NULL,
    notification_type VARCHAR(24) NOT NULL,
    title VARCHAR(150) NOT NULL,
    body VARCHAR(500),
    post_id BIGINT REFERENCES public.posts(post_id) ON DELETE SET NULL,
    comment_id BIGINT REFERENCES public.comments(comment_id) ON DELETE SET NULL,
    dm_message_id BIGINT REFERENCES public.dm_messages(message_id) ON DELETE SET NULL,
    achievement_id BIGINT REFERENCES public.achievement_definitions(achievement_id) ON DELETE SET NULL,
    game_badge_id BIGINT REFERENCES public.game_badges(badge_id) ON DELETE SET NULL,
    event_key VARCHAR(160),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ,
    dismissed_at TIMESTAMPTZ,
    CONSTRAINT chk_user_notifications_type CHECK (
        notification_type IN ('COMMENT', 'REPLY', 'REACTION', 'DM_MESSAGE', 'ACHIEVEMENT', 'SYSTEM')
    ),
    CONSTRAINT chk_user_notifications_one_target CHECK (
        NUM_NONNULLS(post_id, comment_id, dm_message_id, achievement_id, game_badge_id) <= 1
    ),
    CONSTRAINT chk_user_notifications_read_time CHECK (read_at IS NULL OR read_at >= created_at),
    CONSTRAINT chk_user_notifications_dismiss_time CHECK (dismissed_at IS NULL OR dismissed_at >= created_at)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_user_notifications_event
    ON public.user_notifications(receiver_member_id, event_key)
    WHERE event_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_user_notifications_unread
    ON public.user_notifications(receiver_member_id, created_at DESC, notification_id DESC)
    WHERE read_at IS NULL AND dismissed_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_user_notifications_list
    ON public.user_notifications(receiver_member_id, created_at DESC, notification_id DESC);

-- GameZone 배지와 커뮤니티 업적을 마이페이지에서 일관된 스키마로 조회한다.
CREATE OR REPLACE VIEW public.v_member_all_achievements AS
SELECT
    a.member_id,
    'ACHIEVEMENT'::TEXT AS source_type,
    d.achievement_code AS badge_code,
    d.achievement_name AS badge_name,
    d.description::TEXT AS description,
    d.category::TEXT AS category,
    a.awarded_at AS awarded_at
FROM public.member_achievements a
JOIN public.achievement_definitions d ON d.achievement_id = a.achievement_id
UNION ALL
SELECT
    b.member_id,
    'GAME'::TEXT AS source_type,
    d.badge_code,
    d.badge_name,
    d.description::TEXT AS description,
    'GAME'::TEXT AS category,
    b.awarded_at AS awarded_at
FROM public.game_member_badges b
JOIN public.game_badges d ON d.badge_id = b.badge_id;

COMMENT ON TABLE public.user_notifications IS '웹 알림함. Discord DM 발송 큐 notifications와 별개.';
COMMENT ON TABLE public.notification_preferences IS '회원별 웹 알림 수신 설정. 설정 행이 없으면 기본 허용.';

COMMIT;
