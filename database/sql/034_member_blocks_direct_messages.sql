-- PlayMate 034: 회원 차단 + 서비스 내부 1:1 DM (회원 신고 없음)
-- PostgreSQL 18 / prerequisite: public.members
-- Discord 알림 전송 대기열 public.notifications는 수정하지 않는다.
-- 같은 스키마 재실행은 CREATE IF NOT EXISTS로 데이터 변경 없이 통과한다.
BEGIN;

-- A -> B 차단은 방향성을 갖는다. 양쪽 중 한 사람이라도 차단하면 신규 DM을 중단한다.
CREATE TABLE IF NOT EXISTS public.member_blocks (
    blocker_member_id BIGINT NOT NULL REFERENCES public.members(member_id) ON DELETE CASCADE,
    blocked_member_id BIGINT NOT NULL REFERENCES public.members(member_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (blocker_member_id, blocked_member_id),
    CONSTRAINT chk_member_blocks_no_self CHECK (blocker_member_id <> blocked_member_id)
);
CREATE INDEX IF NOT EXISTS idx_member_blocks_blocked
    ON public.member_blocks(blocked_member_id, blocker_member_id);

-- Discord 외부 알림 수신 동의(members.external_dm_opt_in)와 다른 설정이다.
CREATE TABLE IF NOT EXISTS public.member_dm_preferences (
    member_id BIGINT PRIMARY KEY REFERENCES public.members(member_id) ON DELETE CASCADE,
    allow_direct_messages BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 한 쌍의 회원에 대해 대화방 최대 1개. 오름차순 정규화는 API에서 수행한다.
-- 1:1 전용이므로 읽음/보관/음소거 상태를 각 회원의 컬럼으로 보관해 잘못된 참가자를 원천 배제한다.
CREATE TABLE IF NOT EXISTS public.dm_conversations (
    conversation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_low_id BIGINT NOT NULL REFERENCES public.members(member_id),
    member_high_id BIGINT NOT NULL REFERENCES public.members(member_id),
    member_low_read_at TIMESTAMPTZ,
    member_high_read_at TIMESTAMPTZ,
    member_low_archived_at TIMESTAMPTZ,
    member_high_archived_at TIMESTAMPTZ,
    member_low_muted_until TIMESTAMPTZ,
    member_high_muted_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_dm_conversations_order CHECK (member_low_id < member_high_id),
    CONSTRAINT uq_dm_conversations_members UNIQUE (member_low_id, member_high_id)
);
CREATE INDEX IF NOT EXISTS idx_dm_conversations_high_updated
    ON public.dm_conversations(member_high_id, updated_at DESC, conversation_id DESC);
CREATE INDEX IF NOT EXISTS idx_dm_conversations_low_updated
    ON public.dm_conversations(member_low_id, updated_at DESC, conversation_id DESC);

-- UUID는 클라이언트가 재전송해도 같은 메시지가 중복 저장되지 않도록 사용한다.
-- 전역 삭제 시 body=''로 반드시 비워야 한다. 감사 보존 대신 개인정보 최소화를 우선한다.
CREATE TABLE IF NOT EXISTS public.dm_messages (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES public.dm_conversations(conversation_id),
    sender_member_id BIGINT NOT NULL REFERENCES public.members(member_id),
    client_message_id UUID NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    edited_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT uq_dm_messages_idempotency UNIQUE (sender_member_id, client_message_id),
    CONSTRAINT chk_dm_messages_body CHECK (
        (deleted_at IS NULL AND CHAR_LENGTH(body) BETWEEN 1 AND 4000 AND CHAR_LENGTH(BTRIM(body)) > 0)
        OR (deleted_at IS NOT NULL AND body = '')
    )
);
CREATE INDEX IF NOT EXISTS idx_dm_messages_conversation_history
    ON public.dm_messages(conversation_id, message_id DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_dm_messages_sender_created
    ON public.dm_messages(sender_member_id, created_at DESC);

-- 방 생성 자체도 차단/비활성 상태/DM 수신 거절이면 차단한다.
CREATE OR REPLACE FUNCTION public.playmate_dm_conversation_guard()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.member_blocks b
        WHERE (b.blocker_member_id = NEW.member_low_id AND b.blocked_member_id = NEW.member_high_id)
           OR (b.blocker_member_id = NEW.member_high_id AND b.blocked_member_id = NEW.member_low_id)
    ) THEN
        RAISE EXCEPTION '차단 관계에서는 DM 대화를 시작할 수 없습니다.' USING ERRCODE = '23514';
    END IF;
    IF (SELECT COUNT(*) FROM public.members m
        WHERE m.member_id IN (NEW.member_low_id, NEW.member_high_id)
          AND m.member_status = 'ACTIVE') <> 2 THEN
        RAISE EXCEPTION '활성 회원 사이에서만 DM을 시작할 수 있습니다.' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.member_dm_preferences p
        WHERE p.member_id IN (NEW.member_low_id, NEW.member_high_id)
          AND NOT p.allow_direct_messages
    ) THEN
        RAISE EXCEPTION 'DM 수신을 허용하지 않은 회원이 있습니다.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

-- sender_member_id는 실제 대화 참가자만 허용한다. 차단 이후 재발송도 방지한다.
CREATE OR REPLACE FUNCTION public.playmate_dm_message_guard()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    low_id BIGINT;
    high_id BIGINT;
    receiver_id BIGINT;
BEGIN
    SELECT c.member_low_id, c.member_high_id INTO low_id, high_id
    FROM public.dm_conversations c
    WHERE c.conversation_id = NEW.conversation_id;

    IF NOT FOUND OR NEW.sender_member_id NOT IN (low_id, high_id) THEN
        RAISE EXCEPTION 'DM 대화 참가자만 메시지를 보낼 수 있습니다.' USING ERRCODE = '23514';
    END IF;
    receiver_id := CASE WHEN NEW.sender_member_id = low_id THEN high_id ELSE low_id END;

    IF EXISTS (
        SELECT 1 FROM public.member_blocks b
        WHERE (b.blocker_member_id = NEW.sender_member_id AND b.blocked_member_id = receiver_id)
           OR (b.blocker_member_id = receiver_id AND b.blocked_member_id = NEW.sender_member_id)
    ) THEN
        RAISE EXCEPTION '차단 관계에서는 메시지를 보낼 수 없습니다.' USING ERRCODE = '23514';
    END IF;
    IF (SELECT COUNT(*) FROM public.members m
        WHERE m.member_id IN (NEW.sender_member_id, receiver_id)
          AND m.member_status = 'ACTIVE') <> 2 THEN
        RAISE EXCEPTION '활성 회원 사이에서만 메시지를 보낼 수 있습니다.' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.member_dm_preferences p
        WHERE p.member_id = receiver_id AND NOT p.allow_direct_messages
    ) THEN
        RAISE EXCEPTION '수신자가 DM을 허용하지 않았습니다.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

-- 참가자 바꾸기로 검증을 우회할 수 없도록 대화방 참가자 불변.
CREATE OR REPLACE FUNCTION public.playmate_dm_conversation_members_immutable()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.member_low_id IS DISTINCT FROM OLD.member_low_id
       OR NEW.member_high_id IS DISTINCT FROM OLD.member_high_id THEN
        RAISE EXCEPTION '대화방 참가자는 변경할 수 없습니다.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;


-- 메시지의 소속 대화방/발신자/클라이언트 중복키는 수정할 수 없다.
CREATE OR REPLACE FUNCTION public.playmate_dm_message_identity_immutable()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.conversation_id IS DISTINCT FROM OLD.conversation_id
       OR NEW.sender_member_id IS DISTINCT FROM OLD.sender_member_id
       OR NEW.client_message_id IS DISTINCT FROM OLD.client_message_id THEN
        RAISE EXCEPTION '메시지 식별자와 발신자는 변경할 수 없습니다.' USING ERRCODE = '23514';
    END IF;
    IF OLD.deleted_at IS NOT NULL AND NEW.deleted_at IS NULL THEN
        RAISE EXCEPTION '삭제된 DM 메시지는 복구할 수 없습니다.' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

-- 새 메시지를 기록하면 대화방 목록이 최신순으로 갱신된다.
CREATE OR REPLACE FUNCTION public.playmate_dm_message_bump_conversation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    UPDATE public.dm_conversations
    SET updated_at = GREATEST(updated_at, NEW.created_at)
    WHERE conversation_id = NEW.conversation_id;
    RETURN NULL;
END;
$$;

-- 재실행해도 중복 트리거를 만들지 않는다.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.dm_conversations'::regclass
          AND tgname = 'trg_playmate_dm_conversation_guard') THEN
        CREATE TRIGGER trg_playmate_dm_conversation_guard
            BEFORE INSERT ON public.dm_conversations
            FOR EACH ROW EXECUTE FUNCTION public.playmate_dm_conversation_guard();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.dm_conversations'::regclass
          AND tgname = 'trg_playmate_dm_conversation_members_immutable') THEN
        CREATE TRIGGER trg_playmate_dm_conversation_members_immutable
            BEFORE UPDATE ON public.dm_conversations
            FOR EACH ROW EXECUTE FUNCTION public.playmate_dm_conversation_members_immutable();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.dm_messages'::regclass
          AND tgname = 'trg_playmate_dm_message_guard') THEN
        CREATE TRIGGER trg_playmate_dm_message_guard
            BEFORE INSERT ON public.dm_messages
            FOR EACH ROW EXECUTE FUNCTION public.playmate_dm_message_guard();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.dm_messages'::regclass
          AND tgname = 'trg_playmate_dm_message_identity_immutable') THEN
        CREATE TRIGGER trg_playmate_dm_message_identity_immutable
            BEFORE UPDATE ON public.dm_messages
            FOR EACH ROW EXECUTE FUNCTION public.playmate_dm_message_identity_immutable();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.dm_messages'::regclass
          AND tgname = 'trg_playmate_dm_message_bump_conversation') THEN
        CREATE TRIGGER trg_playmate_dm_message_bump_conversation
            AFTER INSERT ON public.dm_messages
            FOR EACH ROW EXECUTE FUNCTION public.playmate_dm_message_bump_conversation();
    END IF;
END;
$$;

COMMENT ON TABLE public.member_blocks IS '회원 간 단방향 차단. 회원 신고 기능은 존재하지 않음.';
COMMENT ON TABLE public.dm_conversations IS '서비스 내부 1:1 DM 대화방. Discord 외부 알림과 별개.';
COMMENT ON TABLE public.dm_messages IS '메시지 서버 저장 이력. 삭제 시 본문을 반드시 비움.';

COMMIT;
