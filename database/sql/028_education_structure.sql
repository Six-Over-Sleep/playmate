-- PlayMate 전국 교육기관 DB 확장
-- PostgreSQL 18
-- 기존 테이블 수정 및 기존 회원 데이터 변경 없음

BEGIN;

CREATE TABLE IF NOT EXISTS institutions (
    institution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_code VARCHAR(40) NOT NULL UNIQUE,
    institution_name VARCHAR(120) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS campuses (
    campus_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL
        REFERENCES institutions(institution_id),
    campus_code VARCHAR(40) NOT NULL,
    campus_name VARCHAR(120) NOT NULL,
    region_code VARCHAR(30),
    is_online BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (institution_id, campus_code),
    UNIQUE (campus_id, institution_id)
);

CREATE TABLE IF NOT EXISTS programs (
    program_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL
        REFERENCES institutions(institution_id),
    program_code VARCHAR(50) NOT NULL,
    program_name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE')),
    UNIQUE (institution_id, program_code),
    UNIQUE (program_id, institution_id)
);

CREATE TABLE IF NOT EXISTS cohorts (
    cohort_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    institution_id BIGINT NOT NULL,
    program_id BIGINT NOT NULL,
    campus_id BIGINT,
    cohort_no INTEGER NOT NULL CHECK (cohort_no > 0),
    start_date DATE,
    end_date DATE,

    FOREIGN KEY (program_id, institution_id)
        REFERENCES programs(program_id, institution_id),

    FOREIGN KEY (campus_id, institution_id)
        REFERENCES campuses(campus_id, institution_id),

    UNIQUE NULLS NOT DISTINCT (program_id, campus_id, cohort_no),

    CHECK (
        start_date IS NULL
        OR end_date IS NULL
        OR end_date >= start_date
    )
);

CREATE TABLE IF NOT EXISTS member_enrollments (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL
        REFERENCES members(member_id),
    cohort_id BIGINT NOT NULL
        REFERENCES cohorts(cohort_id),
    enrollment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (
            enrollment_status IN (
                'PENDING', 'VERIFIED', 'REJECTED',
                'EXPIRED', 'REVOKED', 'COMPLETED'
            )
        ),
    verified_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (member_id, cohort_id),

    CHECK (
        enrollment_status <> 'VERIFIED'
        OR (verified_at IS NOT NULL AND expires_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS enrollment_verifications (
    verification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enrollment_id BIGINT NOT NULL
        REFERENCES member_enrollments(enrollment_id),
    verification_method VARCHAR(30) NOT NULL
        CHECK (verification_method IN ('MANUAL', 'EMAIL', 'DISCORD_ROLE')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reviewer_member_id BIGINT
        REFERENCES members(member_id),
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_member_enrollments_access
    ON member_enrollments (
        member_id,
        enrollment_status,
        expires_at
    );

CREATE INDEX IF NOT EXISTS idx_enrollment_verifications_pending
    ON enrollment_verifications (created_at)
    WHERE status = 'PENDING';

COMMIT;