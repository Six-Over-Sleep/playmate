def scalar(db, sql):
    return db.execute(text(sql)).scalar()


def test_like_is_idempotent_and_counted_per_member(db):
    reaction_service.like_recruit(db, 1, 1)
    second = reaction_service.like_recruit(db, 1, 1)
    assert second == {"recruit_id": 1, "like_count": 1, "liked_by_me": True}
    assert scalar(db, "SELECT COUNT(*) FROM post_likes WHERE post_id = 10") == 1
    assert reaction_service.like_recruit(db, 1, 2)["like_count"] == 2

    assert reaction_service.unlike_recruit(db, 1, 1) == {
        "recruit_id": 1, "like_count": 1, "liked_by_me": False,
    }
    assert reaction_service.unlike_recruit(db, 1, 1)["like_count"] == 1

    rows = {row["recruit_id"]: row for row in recruit_service.get_recruits(db)}
    assert rows[1]["like_count"] == 1 and rows[2]["like_count"] == 0
    assert rows[1]["participant_count"] == 1 and 3 not in rows

    assert recruit_service.get_recruit(db, 1, 2)["liked_by_me"] is True
    assert recruit_service.get_recruit(db, 1, 1)["liked_by_me"] is False
    assert recruit_service.get_recruit(db, 1)["like_count"] == 1


def test_scrap_is_idempotent(db):
    reaction_service.scrap_recruit(db, 1, 1)
    assert reaction_service.scrap_recruit(db, 1, 1) == {"recruit_id": 1, "scrapped_by_me": True}
    assert scalar(db, "SELECT COUNT(*) FROM post_scraps WHERE post_id = 10") == 1
    assert recruit_service.get_recruit(db, 1, 1)["scrapped_by_me"] is True
    assert recruit_service.get_recruit(db, 1, 2)["scrapped_by_me"] is False
    reaction_service.unscrap_recruit(db, 1, 1)
    assert reaction_service.unscrap_recruit(db, 1, 1)["scrapped_by_me"] is False


@pytest.mark.parametrize(
    "method",
    [reaction_service.like_recruit, reaction_service.scrap_recruit],
)
def test_deleted_recruit_saves_nothing(db, method):
    with pytest.raises(HTTPException) as error:
        method(db, 3, 1)
    assert error.value.status_code == 404
    assert scalar(db, "SELECT COUNT(*) FROM post_likes WHERE post_id = 12") == 0
    assert scalar(db, "SELECT COUNT(*) FROM post_scraps WHERE post_id = 12") == 0


def test_comments_replies_and_placeholder(db):
    def write(member_id, body, parent=None, recruit_id=1):
        return comment_service.create_comment(
            db, recruit_id, member_id, RecruitCommentCreate(body=body, parent_comment_id=parent)
        )

    a = write(1, "A")["comment_id"]
    b = write(2, "B")["comment_id"]
    a1 = write(2, "A-1", a)
    assert a1["parent_comment_id"] == a and a1["author_name"] == "효원"
    b1 = write(3, "B-1", b)
    assert b1["author_name"] == "익명"
    a2 = write(1, "A-2", a)["comment_id"]
    other = write(1, "다른 모임 댓글", recruit_id=2)["comment_id"]

    before = scalar(db, "SELECT COUNT(*) FROM comments")
    cases = [
        (a1["comment_id"], 400),   # 대댓글의 대댓글
        (other, 404),              # 다른 모임의 댓글
        (999999, 404),             # 없는 댓글
    ]
    for parent, status in cases:
        with pytest.raises(HTTPException) as error:
            write(1, "x", parent)
        assert error.value.status_code == status
    assert scalar(db, "SELECT COUNT(*) FROM comments") == before  # rollback으로 저장 안 됨

    listed = comment_service.get_comments(db, 1, 2)
    assert [c["body"] for c in listed] == ["A", "A-1", "A-2", "B", "B-1"]

    with pytest.raises(HTTPException) as error:
        comment_service.update_comment(db, 1, a2, 2, RecruitCommentUpdate(body="남의 글"))
    assert error.value.status_code == 403
    with pytest.raises(HTTPException) as error:
        comment_service.delete_comment(db, 2, a2, 1)   # 다른 모임 경로로 접근
    assert error.value.status_code == 404
    assert comment_service.update_comment(db, 1, a2, 1, RecruitCommentUpdate(body="A-2 수정"))["body"] == "A-2 수정"

    comment_service.delete_comment(db, 1, a, 1)
    listed = comment_service.get_comments(db, 1, 1)
    assert [(c["body"], c["is_deleted"]) for c in listed] == [
        ("", True), ("A-1", False), ("A-2 수정", False), ("B", False), ("B-1", False),
    ]
    assert listed[0]["author_id"] is None and listed[0]["is_owner"] is False
    with pytest.raises(HTTPException) as error:
        write(2, "삭제된 부모에 답글", a)
    assert error.value.status_code == 404

    comment_service.delete_comment(db, 1, a1["comment_id"], 2)
    comment_service.delete_comment(db, 1, a2, 1)
    assert [c["body"] for c in comment_service.get_comments(db, 1, 1)] == ["B", "B-1"]
    assert scalar(db, "SELECT COUNT(*) FROM comments WHERE deleted_at IS NOT NULL") == 3
