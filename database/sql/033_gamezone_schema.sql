-- 08. Read-only ranking views, derived from authoritative finalized results.
-- Client should order by best_score / best_wpm / fastest_ms depending on game mode.
CREATE OR REPLACE VIEW public.v_game_member_rankings AS
SELECT
    r.member_id,
    m.game_id,
    mp.cohort_id,
    p.institution_id,
    COUNT(*)::BIGINT AS games_played,
    SUM(r.score)::NUMERIC AS total_score,
    MAX(r.score)::BIGINT AS best_score,
    MIN(r.duration_ms)::BIGINT AS fastest_ms,
    MAX(r.wpm)::NUMERIC AS best_wpm,
    MAX(r.finalized_at) AS last_played_at
FROM public.game_results AS r
JOIN public.game_matches AS m ON m.match_id = r.match_id
JOIN public.game_match_players AS mp ON mp.match_id = r.match_id AND mp.member_id = r.member_id
JOIN public.cohorts AS c ON c.cohort_id = mp.cohort_id
JOIN public.programs AS p ON p.program_id = c.program_id
WHERE r.is_valid = TRUE AND m.status = 'FINISHED'
GROUP BY r.member_id, m.game_id, mp.cohort_id, p.institution_id;

CREATE OR REPLACE VIEW public.v_game_weekly_cohort_scores AS
SELECT
    e.event_id,
    t.event_team_id,
    t.cohort_id,
    COUNT(DISTINCT r.member_id)::BIGINT AS participants,
    COUNT(r.match_id)::BIGINT AS completed_games,
    COALESCE(SUM(r.score),0)::NUMERIC AS total_score
FROM public.game_events AS e
JOIN public.game_event_teams AS t ON t.event_id = e.event_id
LEFT JOIN public.game_matches AS m
    ON m.event_id = e.event_id AND m.status = 'FINISHED'
LEFT JOIN public.game_match_players AS mp
    ON mp.match_id = m.match_id AND mp.event_team_id = t.event_team_id
LEFT JOIN public.game_results AS r
    ON r.match_id = mp.match_id AND r.member_id = mp.member_id AND r.is_valid = TRUE
WHERE e.event_type = 'WEEKLY_COHORT'
GROUP BY e.event_id, t.event_team_id, t.cohort_id;


-- Daily quiz scores are computed per member/event; replays do not inflate the official maximum.
CREATE OR REPLACE VIEW public.v_game_daily_quiz_scores AS
SELECT
    e.event_id,
    e.event_date,
    r.member_id,
    mp.cohort_id,
    MAX(r.score)::BIGINT AS best_score,
    MIN(r.duration_ms)::BIGINT AS fastest_ms,
    COUNT(*)::BIGINT AS completed_runs
FROM public.game_events AS e
JOIN public.game_matches AS m ON m.event_id = e.event_id AND m.status = 'FINISHED'
JOIN public.game_results AS r ON r.match_id = m.match_id AND r.is_valid = TRUE
JOIN public.game_match_players AS mp
    ON mp.match_id = r.match_id AND mp.member_id = r.member_id
JOIN public.game_event_entries AS ee
    ON ee.event_id = e.event_id AND ee.member_id = r.member_id
   AND ee.entry_status = 'COMPLETED'
WHERE e.event_type = 'DAILY_QUIZ'
GROUP BY e.event_id, e.event_date, r.member_id, mp.cohort_id;

