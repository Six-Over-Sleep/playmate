class FakeMember:
    def __init__(self, member_id):
        self.id = member_id

    def __hash__(self):
        return hash(self.id)

    def __eq__(self, other):
        return getattr(other, "id", None) == self.id


class FakeChannel:
    """텍스트 채널 또는 카테고리. 카테고리를 지워도 하위 채널은 남는다 (Discord와 같다)."""

    def __init__(self, guild, channel_id, name, channel_type, category=None, topic=None, overwrites=None):
        self.guild, self.id, self.name, self.type = guild, channel_id, name, channel_type
        self.category, self.topic = category, topic
        self.overwrites = dict(overwrites or {})
        self._children = []
        self.sent = []
        self.fail_send = None
        self.messages = []  # 최신순 Discord 기록 (created_at, author.bot)

    @property
    def channels(self):
        return [c for c in self._children if c.id not in self.guild.cache_miss_ids]

    async def set_permissions(self, target, overwrite=None):
        if overwrite is None:
            self.overwrites.pop(target, None)
        else:
            self.overwrites[target] = overwrite
        self.perm_writes = getattr(self, "perm_writes", 0) + 1

    async def history(self, limit=None):
        for message in self.messages:
            yield message

    async def send(self, text):
        if self.fail_send is not None:
            raise self.fail_send
        self.sent.append(text)
        await self.guild._hook(self.guild.on_send)

    async def delete(self, reason=None):
        await self.guild._hook(self.guild.on_delete)
        self.guild.delete_calls += 1
        if self.id in self.guild.fail_delete_ids:
            raise discord.HTTPException(SimpleNamespace(status=500, reason="x"), "delete boom")
        self.guild.deleted_ids.append(self.id)
        self.guild.channels.pop(self.id, None)
        if self.category is not None and self in self.category._children:
            self.category._children.remove(self)


class FakeGuild:
    def __init__(self):
        self.default_role = discord.Object(id=0, type=discord.Role)
        self.channels = {}
        self.next_id = 1000
        self.absent = set()
        self.fail_create_channel = False
        self.fail_delete_ids = set()
        self.delete_calls = 0
        self.deleted_ids = []
        self.created_channels = 0
        self.created_categories = 0
        self.cache_miss_ids = set()
        self.fetch_errors = {}
        self.hang_ids = set()
        self.on_fetch_member = None
        self.on_delete = None
        self.on_send = None
        self.after_create_channel = None

    def _id(self):
        self.next_id += 1
        return self.next_id

    @property
    def categories(self):
        return [c for c in self.channels.values() if c.type is discord.ChannelType.category]

    @property
    def text_channels(self):
        return [c for c in self.channels.values() if c.type is discord.ChannelType.text]

    def get_channel(self, channel_id):
        if channel_id in self.cache_miss_ids:
            return None
        return self.channels.get(channel_id)

    async def _hook(self, hook):
        if hook:
            result = hook()
            if inspect.isawaitable(result):
                await result

    async def fetch_member(self, member_id):
        await self._hook(self.on_fetch_member)
        if member_id in self.absent:
            raise discord.NotFound(SimpleNamespace(status=404, reason="x"), "x")
        return FakeMember(member_id)

    async def fetch_channel(self, channel_id):
        if channel_id in self.hang_ids:
            await asyncio.sleep(20)  # 제때 응답하지 않는 Discord API
        if channel_id in self.fetch_errors:
            raise self.fetch_errors[channel_id]
        if channel_id not in self.channels:
            raise discord.NotFound(SimpleNamespace(status=404, reason="x"), "unknown channel")
        return self.channels[channel_id]

    async def create_category(self, name, overwrites=None):
        self.created_categories += 1
        category = FakeChannel(self, self._id(), name, discord.ChannelType.category)
        self.channels[category.id] = category
        return category

    async def create_text_channel(self, name, category=None, topic=None, overwrites=None):
        if self.fail_create_channel:
            raise discord.HTTPException(SimpleNamespace(status=500, reason="x"), "boom")
        channel = FakeChannel(self, self._id(), name, discord.ChannelType.text,
                              category=category, topic=topic, overwrites=overwrites)
        if category is not None:
            category._children.append(channel)
        self.channels[channel.id] = channel
        self.created_channels += 1
        if self.after_create_channel:
            self.after_create_channel()
        return channel

    def meeting_channels(self):
        return [c for c in self.text_channels if (c.topic or "").startswith("PlayMate 모임 #")]


class LostResponseConn:
    """문장을 실제로 실행한 뒤, 응답이 도착하지 않은 것처럼 실패하는 연결 (commit은 실제로 됨)."""

    def __init__(self, real, trigger):
        self.real, self.trigger = real, trigger
        self.in_transaction = False

    closed = property(lambda self: self.real.closed)

    def close(self):
        self.real.close()

    def cursor(self):
        return LostResponseCursor(self.real.cursor(), self)

    def transaction(self):
        return LostResponseTransaction(self)


class LostResponseTransaction:
    def __init__(self, owner):
        self.owner, self.inner = owner, owner.real.transaction()

    def __enter__(self):
        self.owner.in_transaction = True
        self.inner.__enter__()
        return self

    def __exit__(self, *exc):
        result = self.inner.__exit__(*exc)  # COMMIT은 실제로 일어난다
        self.owner.in_transaction = False
        if not exc[0] and self.owner.trigger.get("lost_commit"):
            self.owner.trigger["lost_commit"] = False
            raise psycopg.OperationalError("commit reply lost")
        return result


class LostResponseCursor:
    def __init__(self, cur, owner):
        self.cur, self.owner = cur, owner

    def __enter__(self):
        self.cur.__enter__()
        return self

    def __exit__(self, *exc):
        return self.cur.__exit__(*exc)

    def execute(self, sql, params=None):
        self.cur.execute(sql, params)
        trigger = self.owner.trigger
        if trigger["armed"] and trigger["match"] in sql:
            trigger["armed"] = False
            if self.owner.in_transaction:
                trigger["lost_commit"] = True  # 트랜잭션이 commit될 때 실패시킨다
            else:
                raise psycopg.OperationalError("response lost after commit")

    def __getattr__(self, name):
        return getattr(self.cur, name)


class BackendUpdate:
    """두 번째 연결이 Backend 역할로 recruit_mode를 대상이 아닌 값으로 바꾸려는 UPDATE."""

    def __init__(self, recruit_id):
        self.recruit_id = recruit_id
        self.conn = psycopg.connect(DSN, options=DB_OPTIONS)
        self.task = None
        self.blocked = None

    def start(self):
        self.task = asyncio.create_task(asyncio.to_thread(
            self.conn.execute, "UPDATE recruits SET recruit_mode='group' WHERE recruit_id=%s", (self.recruit_id,)))

    async def probe(self, seconds=0.7):
        await asyncio.sleep(seconds)
        self.blocked = not self.task.done()

    async def finish(self):
        await self.task
        self.conn.commit()
        self.conn.close()


