    conn.execute("INSERT INTO recruit_members VALUES (84,9,'MEMBER','JOINED')")
    await sync.run_once()
    guild.cache_miss_ids = set()
    check(all(_joined_ok(loc, 9009) for loc in (cat84, text84, voice84)),
          "참여(JOINED)도 이동/캐시미스 채널까지 저장된 ID 기준으로 부여")

    # PM6) the stored text channel really does not exist (fetch NotFound): the rest is still handled
    cat85, text85, voice85 = await joined_then_canceled(85, "text없음")
    cancel_member(85)
    await text85.delete()
    guild.cache_miss_ids = {text85.id}
    await sync.run_once()
    guild.cache_miss_ids = set()
    check(all(_revoked_ok(loc, 9009, "PUBLIC") for loc in (cat85, voice85)),
          "fetch NotFound인 리소스는 없음으로 보고 나머지 위치는 계속 회수")

    # PM7) Forbidden / HTTPException while resolving: never treated as done, retried next poll
    for number, kind, pick in ((86, "Forbidden", "text"), (87, "HTTPException", "voice")):
        category, text, voice = await joined_then_canceled(number, f"권한조회오류{kind}")
        cancel_member(number)
        target = text if pick == "text" else voice
        guild.cache_miss_ids = {target.id}
        guild.fetch_errors = {target.id: fetch_failure(kind)}
        reachable = [loc for loc in (category, text, voice) if loc is not target]
        await sync.run_once()
        first_poll_writes = writes_of(*reachable)
        await sync.run_once()
        check(_member_has_access(target, 9009),
              f"fetch {kind}: 회수 완료로 오판하지 않음")
        check(all(_revoked_ok(loc, 9009, "PUBLIC") for loc in reachable)
              and writes_of(*reachable) > first_poll_writes,
              f"fetch {kind}: 조회 가능한 위치는 회수하되 매 poll 재시도(완료로 보지 않음)")
        guild.cache_miss_ids = set()
        guild.fetch_errors = {}
        await sync.run_once()
        check(all(_revoked_ok(loc, 9009, "PUBLIC") for loc in (category, text, voice)),
              f"{kind} 해소 후 다음 poll에서 재시도되어 회수 완료")

    # === lock acquisition must survive task cancellation without leaking =================
    def idle_in_tx():
        return conn.execute(
            "SELECT count(*) FROM pg_stat_activity WHERE datname=current_database() "
            "AND state LIKE 'idle in transaction%' AND pid<>pg_backend_pid()").fetchone()[0]

    def session_count():
        return conn.execute(
            "SELECT count(*) FROM pg_stat_activity WHERE datname=current_database()").fetchone()[0]

    def mode_update_is_immediate(recruit_id):
        """Another connection can change recruit_mode right away (no row lock left behind)."""
        other = psycopg.connect(DSN, autocommit=True, options=db_options + " -c lock_timeout=1000")
        try:
            other.execute("UPDATE recruits SET recruit_mode='regular' WHERE recruit_id=%s", (recruit_id,))
            return True
        except psycopg.errors.LockNotAvailable:
            return False
        finally:
            other.close()

    row, cat90 = await create_space(90, "락취소")

    async def hold_lock_body(lock):
        async with lock:
            await asyncio.sleep(30)

    # LC1) blocker holds the row, Bot waits, Bot is cancelled, blocker releases (worker acquires late)
    holder = psycopg.connect(DSN, options=db_options)
    holder.execute("UPDATE recruits SET recruit_mode='regular' WHERE recruit_id=90")
    lock_repo = PostgresMeetingRepository(connect)
    lock_repo.lock_timeout_ms = 4000
    # keep the lock object referenced: a garbage-collected connection would hide a leak
    kept_locks = [lock_repo.regular_lock(90)]
    waiting_task = asyncio.create_task(hold_lock_body(kept_locks[0]))
    await asyncio.sleep(0.5)
    check(not waiting_task.done(), "다른 connection이 row를 잡고 있어 Bot acquire가 대기")
    waiting_task.cancel()
    try:
        await waiting_task
    except asyncio.CancelledError:
        pass
    holder.rollback()  # the worker thread may now acquire the lock "too late"
    holder.close()
    await asyncio.sleep(1.0)
    check(idle_in_tx() == 0, "cancel 후 늦게 락을 얻은 worker가 transaction을 정리: 열린 transaction 0")
    check(mode_update_is_immediate(90), "cancel 후 다른 connection의 recruit_mode UPDATE가 즉시 가능")

    # LC2) repeated cancels at different moments: no leaked sessions
    await asyncio.sleep(0.3)
    baseline = session_count()
    for delay in (0.0, 0.05, 0.3, 0.3, 1.0):
        holder = psycopg.connect(DSN, options=db_options)
        holder.execute("UPDATE recruits SET recruit_mode='regular' WHERE recruit_id=90")
        kept_locks.append(lock_repo.regular_lock(90))
        waiting_task = asyncio.create_task(hold_lock_body(kept_locks[-1]))
        await asyncio.sleep(delay)
        waiting_task.cancel()
        try:
            await waiting_task
        except asyncio.CancelledError:
            pass
        holder.rollback()
        holder.close()
        await asyncio.sleep(0.6)
    check(idle_in_tx() == 0 and session_count() <= baseline, "반복 cancel에도 transaction/connection 누수 없음")
    check(mode_update_is_immediate(90), "반복 cancel 후에도 recruit_mode UPDATE가 즉시 가능")

    # LC3) cancelled while the Bot is inside the locked section
    kept_locks.append(lock_repo.regular_lock(90))
    inside_task = asyncio.create_task(hold_lock_body(kept_locks[-1]))
    await asyncio.sleep(0.5)
    check(mode_update_is_immediate(90) is False, "락 보유 중에는 recruit_mode UPDATE가 대기해야 함")
    inside_task.cancel()
    try:
        await inside_task
    except asyncio.CancelledError:
        pass
    await asyncio.sleep(0.3)
    check(idle_in_tx() == 0 and mode_update_is_immediate(90), "락 보유 중 cancel: 즉시 해제")

    # LC4) cancel handled after the worker had already finished acquiring (ownership hand-over)
    handover = _PostgresRegularLock(lock_repo, 90)
    await asyncio.to_thread(handover._acquire)  # lock held, nobody is awaiting the result
    check(idle_in_tx() == 1, "인수인계 시험: 락 세션이 열려 있음")
    handover._abandon()
    check(idle_in_tx() == 0 and mode_update_is_immediate(90), "이미 획득을 마친 뒤 cancel: 소유자가 해제")

    # === one total timeout for the whole delete section ===================================
    row, cat95 = await create_space(95, "전체타임아웃")
    make_due(95)
    guild.hang_ids = {cat95.id, *(c.id for c in cat95.channels)}
    original_budget = lifecycle.DISCORD_LOCK_HOLD_SECONDS
    lifecycle.DISCORD_LOCK_HOLD_SECONDS = 0.8
    started_at = time.monotonic()
    await lifecycle.check_meeting_lifecycle(client, lifecycle_repo())
    elapsed = time.monotonic() - started_at
    lifecycle.DISCORD_LOCK_HOLD_SECONDS = original_budget
    check(elapsed < 6, "최종 확인 fetch가 멈춰도 total timeout 후 cycle이 종료됨")
    check(row_of(95)["discord_deleted_at"] is None, "timeout 시 mark_deleted 미실행")
    check(idle_in_tx() == 0 and mode_update_is_immediate(95), "timeout 후 transaction rollback/close, row lock 해제")
    guild.hang_ids = set()
    await lifecycle.check_meeting_lifecycle(client, lifecycle_repo())
    check(row_of(95)["discord_deleted_at"] is not None, "다음 lifecycle cycle에서 재시도되어 완료")

    # === mark_deleted lives and dies with the lock's transaction ==========================
    def block_record_row(recruit_id):
        """Another connection holds the discord row, so mark_deleted's UPDATE has to wait."""
        blocker = psycopg.connect(DSN, options=db_options)
        blocker.execute("UPDATE recruit_discord_channels SET updated_at = updated_at WHERE recruit_id=%s",
                        (recruit_id,))
        return blocker

    def space_ids(category):
        return [category.id, *(c.id for c in category.channels)]

    # TX-A) the write waits in the DB, the total timeout fires, the blocker is released later
    row, cat100 = await create_space(100, "지연commit")
    ids100 = space_ids(cat100)
    make_due(100)
    blocker = block_record_row(100)
    original_budget = lifecycle.DISCORD_LOCK_HOLD_SECONDS
    lifecycle.DISCORD_LOCK_HOLD_SECONDS = 2.5
    started_at = time.monotonic()
    await lifecycle.check_meeting_lifecycle(client, lifecycle_repo())
    elapsed = time.monotonic() - started_at
    lifecycle.DISCORD_LOCK_HOLD_SECONDS = original_budget
    check(all(i not in guild.channels for i in ids100), "timeout 시나리오: Discord 삭제 자체는 성공")
    check(elapsed < 10, "mark_deleted가 DB에서 대기해도 total timeout 후 lifecycle 작업이 종료")
    check(row_of(100)["discord_deleted_at"] is None, "timeout 시 discord_deleted_at 미기록")
    check(idle_in_tx() == 1, "timeout 후 blocker 외에 열린 transaction이 없음(rollback/close)")
    blocker.rollback()
    blocker.close()
    await asyncio.sleep(3.0)
    check(row_of(100)["discord_deleted_at"] is None, "blocker 해제 후 충분히 기다려도 뒤늦게 기록되지 않음")
    check(idle_in_tx() == 0 and mode_update_is_immediate(100),
          "timeout 후 열린 transaction 0, 다른 connection의 recruit_mode UPDATE 즉시 가능")

    # TX-B) the lifecycle task is cancelled while mark_deleted waits in the DB
    row, cat101 = await create_space(101, "cancel지연commit")
    make_due(101)
    blocker = block_record_row(101)
    # A long DB lock_timeout would otherwise end the waiting SQL by itself (5s) and hide a
    # missing query cancel; here only the explicit cancel (or statement_timeout ~28s) can.
    patient_repo = lifecycle_repo()
    patient_repo.lock_timeout_ms = 120000
    running_cycle = asyncio.create_task(lifecycle.check_meeting_lifecycle(client, patient_repo))
    await asyncio.sleep(2.5)
    check(not running_cycle.done(), "mark_deleted가 DB에서 대기 중인 상태")
    cancelled_at = time.monotonic()
    running_cycle.cancel()
    try:
        await running_cycle
    except asyncio.CancelledError:
        pass
    check(time.monotonic() - cancelled_at < 8, "cancel 시 진행 중인 SQL을 서버에서 취소해 빠르게 정리")
    check(idle_in_tx() == 1, "cancel 후 blocker 외에 열린 transaction이 없음")
    blocker.rollback()
    blocker.close()
    await asyncio.sleep(3.0)
    check(row_of(101)["discord_deleted_at"] is None, "cancel 후 blocker 해제해도 뒤늦게 기록되지 않음")
    check(idle_in_tx() == 0 and mode_update_is_immediate(101),
          "cancel 후 열린 transaction 0, recruit_mode UPDATE 즉시 가능")

    # TX-C) normal path: same transaction, visible to others only after COMMIT
    row, cat102 = await create_space(102, "같은transaction")
    make_due(102)
    seen = {}
    real_lock_mark = _PostgresRegularLock.mark_deleted

    async def observing_mark(self, category_id, now, timeout_seconds=None):
        seen["result"] = await real_lock_mark(self, category_id, now, timeout_seconds)
        seen["before_commit"] = row_of(102)["discord_deleted_at"]  # read by ANOTHER connection
        return seen["result"]

    _PostgresRegularLock.mark_deleted = observing_mark
    await lifecycle.check_meeting_lifecycle(client, lifecycle_repo())
    _PostgresRegularLock.mark_deleted = real_lock_mark
    check(seen.get("result") is True and seen.get("before_commit") is None,
          "mark_deleted는 lock과 같은 transaction에서 실행되어 COMMIT 전에는 다른 connection에 보이지 않음")
    check(row_of(102)["discord_deleted_at"] is not None and all(i not in guild.channels for i in space_ids(cat102)),
          "세 리소스 삭제 확인 후 COMMIT되어 discord_deleted_at이 기록됨")
    check(idle_in_tx() == 0, "정상 경로 후 열린 transaction 0")

    # TX-D) the UPDATE ran, then the block fails: the whole transaction is rolled back
    row, cat103 = await create_space(103, "write후실패")
    make_due(103)

    async def write_then_fail(self, category_id, now, timeout_seconds=None):
        await real_lock_mark(self, category_id, now, timeout_seconds)
        raise RuntimeError("fails after the UPDATE ran")

    _PostgresRegularLock.mark_deleted = write_then_fail
    await lifecycle.check_meeting_lifecycle(client, lifecycle_repo())
    _PostgresRegularLock.mark_deleted = real_lock_mark
    check(row_of(103)["discord_deleted_at"] is None, "UPDATE 실행 후 실패하면 transaction 전체 rollback")
    check(idle_in_tx() == 0 and mode_update_is_immediate(103), "실패 후 row lock 해제")
    await lifecycle.check_meeting_lifecycle(client, lifecycle_repo())
    check(row_of(103)["discord_deleted_at"] is not None, "다음 lifecycle cycle에서 재시도되어 기록")

    # TX-E) the SQL itself is bounded by the remaining budget (server-side statement_timeout)
    row, cat104 = await create_space(104, "statement_timeout")
    blocker = block_record_row(104)
    probe_lock = lock_repo.regular_lock(104)
    started_at = time.monotonic()
    canceled = None
    try:
        async with probe_lock:
            await asyncio.wait_for(probe_lock.mark_deleted(cat104.id, datetime.now(KST), 1.0), 12)
    except psycopg.errors.QueryCanceled as error:
        canceled = error
    except asyncio.TimeoutError:
        canceled = None
    check(canceled is not None and time.monotonic() - started_at < 8,
          "남은 budget(1초)을 server-side statement_timeout으로 적용해 SQL이 제때 끝남")
    blocker.rollback()
    blocker.close()
    await asyncio.sleep(0.5)
    check(row_of(104)["discord_deleted_at"] is None and idle_in_tx() == 0, "statement timeout 후에도 기록/누수 없음")

    # TX-F) cleanup ownership: the session is not rolled back/closed while a worker thread
    # still runs a statement on its connection; it is only released once that worker is done
    held_lock = lock_repo.regular_lock(90)
    await asyncio.to_thread(held_lock._acquire)
    held_lock._stmt_idle.clear()  # pretend a worker thread is still executing a statement
    closing = asyncio.create_task(asyncio.to_thread(held_lock._finalize, False))
    await asyncio.sleep(0.7)
    check(not closing.done() and idle_in_tx() == 1,
          "worker가 SQL을 끝내기 전에는 같은 connection을 rollback/close 하지 않음")
    held_lock._stmt_idle.set()
    await closing
    check(idle_in_tx() == 0 and mode_update_is_immediate(90), "worker 종료 후에만 정리되고 락이 풀림")

    # --- concurrent claim -------------------------------------------------------
    conn.execute("INSERT INTO posts (post_id,title,post_status) OVERRIDING SYSTEM VALUE VALUES (7,'동시',NULL)")
    conn.execute("INSERT INTO recruits (recruit_id,post_id,recruit_mode,state) OVERRIDING SYSTEM VALUE VALUES (7,7,'regular','OPEN')")
    claims = [PostgresMeetingRepository(connect).claim_provisioning(7) for _ in range(3)]
    check(claims.count(True) == 1, "동시 선점은 한 곳만 성공")

    leaked = conn.execute(
        "SELECT count(*) FROM pg_stat_activity WHERE datname = current_database() "
        "AND state LIKE 'idle in transaction%' AND pid <> pg_backend_pid()").fetchone()[0]
    check(leaked == 0, "row lock 세션이 끝난 뒤 열린 트랜잭션/연결이 남지 않음")
    conn.close()
    admin.execute("DROP SCHEMA bot_test CASCADE")
    admin.close()
    print(f"PASS: {checks} DB integration assertions passed.")


