-- PostgreSQL 18 / PlayMate GameZone: quizzes, coding games, duels, cohort leagues, rankings, badges
-- Prerequisites: members, institutions/programs/cohorts, member_enrollments (028-032)
-- No study rooms or study timers. This migration does not modify existing member XP balances.
-- For a dry run, execute a COPY of the whole script with the final COMMIT replaced by ROLLBACK.
BEGIN;

-- 01. Category taxonomy and discoverable game catalog
CREATE TABLE IF NOT EXISTS public.game_categories (
    category_code VARCHAR(30) PRIMARY KEY,
    category_name VARCHAR(60) NOT NULL,
    sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.games (
    game_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(80) NOT NULL UNIQUE,
    title VARCHAR(120) NOT NULL,
    description TEXT,
    category_code VARCHAR(30) NOT NULL REFERENCES public.game_categories(category_code),
    game_type VARCHAR(20) NOT NULL CHECK (game_type IN ('QUIZ','CODE','BUG_HUNT','TYPING','MINI')),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
    rules JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(rules) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$')
);

CREATE TABLE IF NOT EXISTS public.game_supported_modes (
    game_id BIGINT NOT NULL REFERENCES public.games(game_id) ON DELETE CASCADE,
    game_mode VARCHAR(12) NOT NULL CHECK (game_mode IN ('SOLO','DUEL','TEAM')),
    PRIMARY KEY (game_id, game_mode)
);

-- 02. Question bank. Secrets are in a separate table to prevent accidental API leakage.
CREATE TABLE IF NOT EXISTS public.game_questions (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES public.games(game_id),
    category_code VARCHAR(30) NOT NULL REFERENCES public.game_categories(category_code),
    question_type VARCHAR(20) NOT NULL CHECK (question_type IN ('QUIZ','CODE','BUG_HUNT','TYPING')),
    difficulty SMALLINT NOT NULL DEFAULT 1 CHECK (difficulty BETWEEN 1 AND 5),
    prompt TEXT NOT NULL CHECK (length(btrim(prompt)) > 0),
    public_payload JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(public_payload) = 'object'),
    default_points INTEGER NOT NULL DEFAULT 10 CHECK (default_points > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PUBLISHED','ARCHIVED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.game_question_secrets (
    question_id BIGINT PRIMARY KEY REFERENCES public.game_questions(question_id) ON DELETE CASCADE,
    answer_key JSONB NOT NULL CHECK (jsonb_typeof(answer_key) = 'object'),
    judge_config JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(judge_config) = 'object'),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 03. Events: daily quiz, week-long cohort competition, other limited-time events.
-- event_date is the Asia/Seoul calendar date selected by the backend for daily quizzes.
CREATE TABLE IF NOT EXISTS public.game_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(24) NOT NULL CHECK (event_type IN ('DAILY_QUIZ','WEEKLY_COHORT','SEASONAL')),
    game_id BIGINT REFERENCES public.games(game_id),
    title VARCHAR(160) NOT NULL,
    event_date DATE,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
        CHECK (status IN ('SCHEDULED','ACTIVE','FINISHED','CANCELLED')),
    scoring_rules JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(scoring_rules) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (ends_at > starts_at),
    CHECK (
      (event_type = 'DAILY_QUIZ' AND event_date IS NOT NULL AND game_id IS NOT NULL)
      OR (event_type <> 'DAILY_QUIZ' AND event_date IS NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_game_events_daily_quiz
    ON public.game_events(game_id, event_date)
    WHERE event_type = 'DAILY_QUIZ';

CREATE TABLE IF NOT EXISTS public.game_event_questions (
    event_id BIGINT NOT NULL REFERENCES public.game_events(event_id) ON DELETE CASCADE,
    question_id BIGINT NOT NULL REFERENCES public.game_questions(question_id),
    display_order INTEGER NOT NULL CHECK (display_order >= 1),
    points INTEGER NOT NULL CHECK (points > 0),
    PRIMARY KEY (event_id, question_id),
    UNIQUE (event_id, display_order)
);

-- One official entry per member per event (important for daily rewards and weekly leagues).
CREATE TABLE IF NOT EXISTS public.game_event_entries (
    event_id BIGINT NOT NULL REFERENCES public.game_events(event_id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES public.members(member_id),
    cohort_id BIGINT NOT NULL REFERENCES public.cohorts(cohort_id),
    entry_status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED'
        CHECK (entry_status IN ('REGISTERED','COMPLETED','DISQUALIFIED')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    PRIMARY KEY (event_id, member_id),
    CHECK (completed_at IS NULL OR completed_at >= joined_at)
);

-- Each weekly team represents exactly one cohort in that event.
CREATE TABLE IF NOT EXISTS public.game_event_teams (
    event_team_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES public.game_events(event_id) ON DELETE CASCADE,
    cohort_id BIGINT NOT NULL REFERENCES public.cohorts(cohort_id),
    team_name VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (event_id, cohort_id)
);

-- 04. Play session and membership for SOLO / DUEL(1:1) / TEAM.
CREATE TABLE IF NOT EXISTS public.game_matches (
    match_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id BIGINT NOT NULL REFERENCES public.games(game_id),
    game_mode VARCHAR(12) NOT NULL,
    event_id BIGINT REFERENCES public.game_events(event_id),
    host_member_id BIGINT NOT NULL REFERENCES public.members(member_id),
    status VARCHAR(20) NOT NULL DEFAULT 'WAITING'
        CHECK (status IN ('WAITING','RUNNING','FINISHED','CANCELLED','EXPIRED')),
    max_players INTEGER NOT NULL DEFAULT 1 CHECK (max_players BETWEEN 1 AND 200),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (game_id, game_mode)
        REFERENCES public.game_supported_modes(game_id, game_mode),
    CHECK ((game_mode = 'SOLO' AND max_players = 1)
        OR (game_mode = 'DUEL' AND max_players = 2)
        OR (game_mode = 'TEAM' AND max_players >= 2)),
    CHECK (finished_at IS NULL OR (started_at IS NOT NULL AND finished_at >= started_at))
);

CREATE TABLE IF NOT EXISTS public.game_match_players (
    match_id BIGINT NOT NULL REFERENCES public.game_matches(match_id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES public.members(member_id),
    -- Immutable affiliation snapshot, so historical rankings survive graduation/affiliation changes.
    cohort_id BIGINT NOT NULL REFERENCES public.cohorts(cohort_id),
    event_team_id BIGINT REFERENCES public.game_event_teams(event_team_id),
    player_status VARCHAR(20) NOT NULL DEFAULT 'JOINED'
        CHECK (player_status IN ('JOINED','READY','FINISHED','LEFT','DISQUALIFIED')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (match_id, member_id)
);

-- Question attempts / typing submissions / mini-game actions. Idempotent per client request.
CREATE TABLE IF NOT EXISTS public.game_attempts (
    attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    question_id BIGINT REFERENCES public.game_questions(question_id),
    attempt_no INTEGER NOT NULL CHECK (attempt_no >= 1),
    request_id UUID NOT NULL,
    submission JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(submission) = 'object'),
    is_correct BOOLEAN,
    points_awarded INTEGER NOT NULL DEFAULT 0 CHECK (points_awarded >= 0),
    elapsed_ms BIGINT CHECK (elapsed_ms IS NULL OR elapsed_ms >= 0),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (match_id, member_id)
        REFERENCES public.game_match_players(match_id, member_id) ON DELETE CASCADE,
    UNIQUE (match_id, member_id, attempt_no),
    UNIQUE (member_id, request_id),
    CHECK (octet_length(submission::text) <= 65536)
);

-- Official result: one finalized score per participant and match.
-- XP issuance remains in existing member_xp_history, not duplicated here.
CREATE TABLE IF NOT EXISTS public.game_results (
    match_id BIGINT NOT NULL,
    member_id BIGINT NOT NULL,
    score BIGINT NOT NULL DEFAULT 0 CHECK (score >= 0),
    duration_ms BIGINT CHECK (duration_ms IS NULL OR duration_ms >= 0),
    accuracy_pct NUMERIC(5,2) CHECK (accuracy_pct IS NULL OR accuracy_pct BETWEEN 0 AND 100),
    wpm NUMERIC(8,2) CHECK (wpm IS NULL OR wpm >= 0),
    is_valid BOOLEAN NOT NULL DEFAULT TRUE,
    finalized_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (match_id, member_id),
    FOREIGN KEY (match_id, member_id)
        REFERENCES public.game_match_players(match_id, member_id) ON DELETE CASCADE
);

-- 05. GameZone badges; existing member_levels / member_skill_levels handle leveling.
CREATE TABLE IF NOT EXISTS public.game_badges (
    badge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    badge_code VARCHAR(60) NOT NULL UNIQUE,
    badge_name VARCHAR(100) NOT NULL,
    description TEXT,
    award_rule JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(award_rule) = 'object'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.game_member_badges (
    member_id BIGINT NOT NULL REFERENCES public.members(member_id),
    badge_id BIGINT NOT NULL REFERENCES public.game_badges(badge_id),
    source_match_id BIGINT REFERENCES public.game_matches(match_id),
    awarded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (member_id, badge_id)
);

-- 06. Indexes: daily events, eligible questions, live duels, player history/ranking.
CREATE INDEX IF NOT EXISTS idx_game_questions_pool
    ON public.game_questions(game_id, status, difficulty);
CREATE INDEX IF NOT EXISTS idx_game_events_schedule
    ON public.game_events(status, starts_at, ends_at);
CREATE INDEX IF NOT EXISTS idx_game_event_entries_member
    ON public.game_event_entries(member_id, joined_at DESC);
CREATE INDEX IF NOT EXISTS idx_game_event_teams_cohort
    ON public.game_event_teams(cohort_id, event_id);
CREATE INDEX IF NOT EXISTS idx_game_matches_lobby
    ON public.game_matches(game_id, status, created_at DESC)
    WHERE status IN ('WAITING','RUNNING');
CREATE INDEX IF NOT EXISTS idx_game_matches_event
    ON public.game_matches(event_id, status) WHERE event_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_game_players_member
    ON public.game_match_players(member_id, joined_at DESC);
CREATE INDEX IF NOT EXISTS idx_game_players_cohort
    ON public.game_match_players(cohort_id, match_id);
CREATE INDEX IF NOT EXISTS idx_game_attempts_match_player
    ON public.game_attempts(match_id, member_id, submitted_at);
CREATE INDEX IF NOT EXISTS idx_game_results_finalized
    ON public.game_results(finalized_at DESC) WHERE is_valid = TRUE;

