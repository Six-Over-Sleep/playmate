BEGIN;

CREATE TABLE IF NOT EXISTS career_talk_attachments (

    -- 첨부파일 고유 ID
    attachment_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    -- 첨부된 게시글 ID
    post_id BIGINT NOT NULL
        REFERENCES career_talks(post_id)
        ON DELETE CASCADE,

    -- 사용자가 업로드한 원본 파일명
    original_filename VARCHAR(255) NOT NULL,

    -- 서버에 저장된 상대 경로
    -- 예: career/talks/25/abc123.png
    stored_path VARCHAR(500) NOT NULL UNIQUE,

    -- 이미지 또는 일반 파일
    attachment_type VARCHAR(10) NOT NULL
        CHECK (
            attachment_type IN ('IMAGE', 'FILE')
        ),

    -- MIME 타입
    -- 예: image/png, application/pdf
    content_type VARCHAR(100) NOT NULL,

    -- 파일 크기 (Byte)
    file_size_bytes BIGINT NOT NULL
        CHECK (
            file_size_bytes BETWEEN 1 AND 10485760
        ),

    -- 첨부 순서 (1~5)
    display_order SMALLINT NOT NULL
        CHECK (
            display_order BETWEEN 1 AND 5
        ),

    -- 업로드 시각
    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- 같은 게시글에서 첨부 순서 중복 방지
    CONSTRAINT uq_career_talk_attachment_order
        UNIQUE (post_id, display_order)
);

COMMIT;
