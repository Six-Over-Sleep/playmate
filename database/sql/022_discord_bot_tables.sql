-- Discord Bot 필수 테이블 생성 (notifications, recruit_discord_channels)
-- 적용 전 검토용: 공용 DB 적용은 DB 담당자와 협의 후 진행
--
-- 배경
--   notifications           : Backend 모델(backend/app/models/notification.py)만 있고 생성 SQL이 없었다.
--                             Backend가 댓글·대댓글 알림 행을 넣고, Bot이 PENDING 행을 읽어 DM을 보낸다.
--   recruit_discord_channels: Bot 코드와 Bot 테스트 fixture에만 정의가 있었다.
--                             모임 하나당 Discord 채널 하나의 생성·활동·삭제 상태를 Bot이 기록한다.
--
-- 선행 테이블 (이 파일은 만들지 않는다): members, posts, comments, recruits
--
-- 안전 원칙
--   - CREATE TABLE / INDEX IF NOT EXISTS만 사용한다. DROP, TRUNCATE, DELETE, 기존 테이블 ALTER는 없다.
--   - 같은 이름의 테이블이 이미 있으면 이 파일은 그 테이블을 건드리지 않는다.
--     그 경우 구조가 같은지는 보장되지 않으므로 기존 DB에 적용하기 전에 컬럼·자료형·제약조건·인덱스를 실제 DB 구조와 직접 비교한다.
--   - 여러 번 실행해도 안전하다 (두 번째부터는 아무것도 바꾸지 않는다).

BEGIN;

-- 1. DM 알림 대기열 ----------------------------------------------------------
-- status : PENDING(전송 대기) -> SENT / SKIPPED / FAILED. 시각 컬럼은 Backend 모델과 같은 timestamp(시간대 없음)다.
CREATE TABLE IF NOT EXISTS notifications (
    notification_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receiver_member_id BIGINT      NOT NULL REFERENCES members(member_id),
    actor_member_id    BIGINT      NOT NULL REFERENCES members(member_id),
    notification_type  VARCHAR(30) NOT NULL,
    post_id            BIGINT      REFERENCES posts(post_id),
    comment_id         BIGINT      REFERENCES comments(comment_id),
    status             VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    sent_at            TIMESTAMP,
    error_message      TEXT,
    retry_count        INTEGER     NOT NULL DEFAULT 0,
    last_attempt_at    TIMESTAMP,
    created_at         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at         TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_notifications_type
        CHECK (notification_type IN ('COMMENT', 'REPLY', 'REACTION')),
    CONSTRAINT chk_notifications_status
        CHECK (status IN ('PENDING', 'SENT', 'SKIPPED', 'FAILED')),
    CONSTRAINT chk_notifications_retry
        CHECK (retry_count >= 0)
);

-- Bot의 claim_pending이 PENDING 행을 오래된 순으로 읽을 때 사용한다 (Backend 모델과 같은 이름).
CREATE INDEX IF NOT EXISTS idx_notifications_pending
    ON notifications (created_at, notification_id)
    WHERE status = 'PENDING';

-- Backend의 notification_writer가 "같은 댓글의 알림이 이미 있는가"를 확인할 때 사용한다.
CREATE INDEX IF NOT EXISTS idx_notifications_comment
    ON notifications (comment_id)
    WHERE comment_id IS NOT NULL;

-- Bot의 상태 변경 SQL은 updated_at을 직접 바꾸지 않으므로 UPDATE 때 DB가 갱신한다.
-- (이 저장소에는 다른 trigger가 없어 notifications 전용 함수로 둔다.)
CREATE OR REPLACE FUNCTION notifications_set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_trigger
         WHERE tgname = 'trg_notifications_set_updated_at'
           AND tgrelid = 'notifications'::regclass
    ) THEN
        CREATE TRIGGER trg_notifications_set_updated_at
            BEFORE UPDATE ON notifications
            FOR EACH ROW EXECUTE FUNCTION notifications_set_updated_at();
    END IF;
END
$$;

-- 2. 모임 Discord 채널 상태 -------------------------------------------------
-- 모임 하나에 행 하나(recruit_id가 PK)라서 Bot 재시작 후에도 채널이 중복 생성되지 않는다.
-- sync_status : PENDING(생성 선점) / SUCCESS(채널 ID 저장 완료) / FAILED(sync_error 참고, 'MANUAL:'/'ABORTED:'는 자동 재시도 안 함)
-- 시각 컬럼은 Bot이 시간대를 포함해 읽고 쓰므로 timestamptz다.
-- discord_category_id / discord_voice_channel_id는 예전 구조의 컬럼이다. 새 구조에서는 NULL로 두고 읽기만 한다.
CREATE TABLE IF NOT EXISTS recruit_discord_channels (
    recruit_id               BIGINT       PRIMARY KEY REFERENCES recruits(recruit_id),
    discord_category_id      VARCHAR(32),
    discord_text_channel_id  VARCHAR(32),
    discord_voice_channel_id VARCHAR(32),
    sync_status              VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    sync_error               TEXT,
    synced_at                TIMESTAMPTZ,
    last_activity_at         TIMESTAMPTZ,
    inactivity_warned_at     TIMESTAMPTZ,
    scheduled_delete_at      TIMESTAMPTZ,
    discord_deleted_at       TIMESTAMPTZ,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_recruit_discord_channels_category UNIQUE (discord_category_id),
    CONSTRAINT uq_recruit_discord_channels_text     UNIQUE (discord_text_channel_id),
    CONSTRAINT uq_recruit_discord_channels_voice    UNIQUE (discord_voice_channel_id),
    CONSTRAINT chk_recruit_discord_channels_status
        CHECK (sync_status IN ('PENDING', 'SUCCESS', 'FAILED'))
);

COMMIT;

