"""취업게시판 신규 글 자동 공지 DB 통합 테스트: 일회용 PostgreSQL + 가짜 Discord 채널.

database/sql/013_career_discord_announcements.sql을 그대로 적용해 선점·재시작·동시 실행·재시도를 확인한다.
public 스키마의 테이블을 지우고 다시 만들므로 반드시 일회용 DB로 실행한다 (localhost가 아니면 중단).
  docker run -d --rm -e POSTGRES_PASSWORD=test -e POSTGRES_DB=pm -p 127.0.0.1:55432:5432 postgres:16
  PLAYMATE_TEST_PG_DSN="host=127.0.0.1 port=55432 user=postgres password=test dbname=pm"
"""
import asyncio
import os
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import AsyncMock, Mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
DSN = os.environ.get("PLAYMATE_TEST_PG_DSN")
if not DSN:
    print("SKIP: PLAYMATE_TEST_PG_DSN is not set")
    sys.exit(0)
os.environ["DISCORD_BOT_TOKEN"] = "verification-only"
os.environ["DISCORD_GUILD_ID"] = "1"

import discord
import psycopg
from psycopg.conninfo import conninfo_to_dict

if conninfo_to_dict(DSN).get("host") not in ("127.0.0.1", "localhost"):
    sys.exit("일회용 로컬 DB(127.0.0.1/localhost)에서만 실행합니다.")

from config import KST
from repositories.career_notice_repository import PostgresCareerNoticeRepository
from repositories.db import Database
from services.career_notice_service import CareerNoticeService

MIGRATION = ROOT.parent / "database" / "sql" / "013_career_discord_announcements.sql"
BASE = "https://playmate.example.com"
DAY1 = datetime(2026, 10, 28, 18, 0, tzinfo=KST)
checks = 0


def check(condition, label):
    global checks
    assert condition, label
    checks += 1
    print("PASS", label)


def q(sql, params=()):
    with psycopg.connect(DSN, autocommit=True) as conn:
        cur = conn.execute(sql, params)
        return cur.fetchall() if cur.description else []


def new_database():
    """Bot과 같은 연결 옵션 (서울 시간대). 호출할 때마다 새 '프로세스'처럼 별도 연결을 쓴다."""
    return Database(lambda: psycopg.connect(DSN, autocommit=True, options="-c TimeZone=Asia/Seoul"))


def reset_schema():
    q("DROP TABLE IF EXISTS career_discord_announcements, career_posts, posts, members CASCADE")
    q("""CREATE TABLE members (member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nickname VARCHAR(50));
         CREATE TABLE posts (post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, board_id BIGINT,
           author_member_id BIGINT NOT NULL REFERENCES members, post_type VARCHAR(30), title VARCHAR(100) NOT NULL,
           body TEXT, source_type VARCHAR(20), post_status VARCHAR(20), published_at TIMESTAMP,
           created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
           deleted_at TIMESTAMP);
         CREATE TABLE career_posts (post_id BIGINT PRIMARY KEY REFERENCES posts(post_id) ON DELETE CASCADE,
           category_code VARCHAR(20) NOT NULL, subcategory_code VARCHAR(50) NOT NULL,
           is_anonymous BOOLEAN NOT NULL DEFAULT TRUE,
           CONSTRAINT ck_career_posts_category CHECK (category_code IN ('reviews', 'talk', 'lounge', 'lab')));
         INSERT INTO members (nickname) VALUES ('작성자');""")


def add_post(category, title, created_at, status="PUBLISHED", deleted=False):
    """Backend 작성 API와 같은 값(post_type='CAREER', board_id=NULL, post_status='PUBLISHED')으로 저장한다."""
    post_id = q("""INSERT INTO posts (board_id, author_member_id, post_type, title, body, source_type,
                                      post_status, published_at, created_at, deleted_at)
                   VALUES (NULL, 1, 'CAREER', %s, '본문', 'USER', %s, %s, %s, %s) RETURNING post_id""",
                (title, status, created_at, created_at, created_at if deleted else None))[0][0]
    q("INSERT INTO career_posts (post_id, category_code, subcategory_code) VALUES (%s, %s, 'all')",
      (post_id, category))
    return post_id


class FakeChannel:
    def __init__(self):
        self.id = 60
        self.sent = []
        self.fail_ids = set()

    async def send(self, *, embed, allowed_mentions):
        post_id = int(embed.url.rsplit("/", 1)[1])
        if post_id in self.fail_ids:
            raise discord.HTTPException(Mock(status=500), "server error")
        self.sent.append((post_id, embed.url, allowed_mentions))
        return SimpleNamespace(id=9000 + len(self.sent))


def notice_service(channel, database=None, base_url=BASE):
    client = Mock()
    client.get_channel.return_value = channel
    repo = PostgresCareerNoticeRepository(database or new_database())
    return CareerNoticeService(client, repo, channel.id, base_url=base_url), repo


def statuses():
    return dict(q("SELECT post_id, status FROM career_discord_announcements"))


async def main():
    reset_schema()
    utc = datetime(2026, 10, 1, 0, 0)

    # -- 마이그레이션 전: 테이블이 없으면 공지하지 않음 ------------------------------
    old_review = add_post("reviews", "기존 후기", utc)
    old_lab = add_post("lab", "기존 연구소 글", utc + timedelta(minutes=1))
    old_talk = add_post("talk", "기존 톡톡", utc + timedelta(minutes=2))
    channel = FakeChannel()
    service, _ = notice_service(channel)
    check(await service.run(DAY1) == 0 and not channel.sent, "013 미적용: 공지하지 않음")

    # -- 013 적용: 기존 reviews/lab 글은 BASELINE ----------------------------------
    q(MIGRATION.read_text(encoding="utf-8"))
    check(statuses() == {old_review: "BASELINE", old_lab: "BASELINE"},
          "013 적용 시 기존 reviews·lab 글은 BASELINE (talk 제외)")
    check(await service.run(DAY1) == 0 and not channel.sent, "최초 실행: 기존 글 대량 공지 없음, 신규 없으면 미전송")
    q(MIGRATION.read_text(encoding="utf-8"))
    check(len(statuses()) == 2, "013 재실행해도 기준점 중복 없음")

    # -- 신규 글: reviews 4, lab 3, talk/lounge, 삭제, 비공개 -------------------------
    t = datetime(2026, 10, 28, 1, 0)
    reviews = [add_post("reviews", f"후기 {i}", t + timedelta(minutes=10 * i)) for i in range(1, 5)]
    labs = [add_post("lab", f"연구소 {i}", t + timedelta(minutes=10 * i + 5)) for i in range(1, 4)]
    late_id_early_time = add_post("lab", "@everyone 늦게 저장된 오래된 글", t)  # ID는 크지만 작성은 가장 이른 글
    talk = add_post("talk", "톡톡 신규", t + timedelta(minutes=1))
    lounge = add_post("lounge", "라운지 신규", t + timedelta(minutes=2))
    deleted = add_post("reviews", "삭제된 후기", t + timedelta(minutes=3), deleted=True)
    hidden = add_post("lab", "비공개 연구소 글", t + timedelta(minutes=4), status="HIDDEN")

    order = [late_id_early_time, reviews[0], labs[0], reviews[1], labs[1], reviews[2], labs[2], reviews[3]]
    check(await service.run(DAY1) == 5, "하루 최대 5개 공지")
    sent_ids = [post_id for post_id, _, _ in channel.sent]
    check(sent_ids == order[:5], "작성일(created_at), post_id 순으로 오래된 신규 글부터")
    check(channel.sent[0][1] == f"{BASE}/career/lab/{late_id_early_time}"
          and channel.sent[1][1] == f"{BASE}/career/reviews/{reviews[0]}", "원본 상세 URL 정확")
    check(all(not m.everyone and m.users is False and m.roles is False for _, _, m in channel.sent),
          "모든 공지에 멘션 차단")
    rows = q("""SELECT post_id, status, announce_date, attempt_count, discord_channel_id, discord_message_id
                  FROM career_discord_announcements WHERE status = 'SENT' ORDER BY post_id""")
    check(len(rows) == 5 and all(r[2] == DAY1.date() and r[3] == 1 and r[4] == "60" and r[5] for r in rows),
          "SENT: 공지 날짜(KST)·시도 1회·채널·메시지 ID 기록")

    check(await service.run(DAY1 + timedelta(minutes=5)) == 0 and len(channel.sent) == 5,
          "같은 날 다시 실행해도 5개 초과 공지 없음")

    # -- Bot 재시작(새 연결·새 서비스): 이어서 공지, 재공지 없음 -----------------------
    channel2 = FakeChannel()
    restarted, _ = notice_service(channel2)
    day2 = DAY1 + timedelta(days=1)
    check(await restarted.run(day2) == 3 and [p for p, _, _ in channel2.sent] == order[5:],
          "재시작 후 다음 날: 남은 3개만 공지 (누락 없음, 재공지 없음)")
    check(await restarted.run(day2 + timedelta(days=1)) == 0 and len(channel2.sent) == 3,
          "모두 공지한 뒤에는 미전송")
    final = statuses()
    for post_id in (talk, lounge, deleted, hidden):
        check(post_id not in final, f"post {post_id}: talk/lounge/삭제/비공개 글은 공지 대상 아님")

    # -- 실패 → FAILED → 다음 실행 재시도, 부분 실패, 시도 한도 ------------------------
    day4 = DAY1 + timedelta(days=3)
    a = add_post("reviews", "실패 테스트 A", t + timedelta(days=3))
    b = add_post("lab", "실패 테스트 B", t + timedelta(days=3, minutes=1))
    c = add_post("reviews", "실패 테스트 C", t + timedelta(days=3, minutes=2))
    channel3 = FakeChannel()
    channel3.fail_ids = {b}
    svc3, _ = notice_service(channel3)
    check(await svc3.run(day4) == 2 and statuses()[b] == "FAILED"
          and statuses()[a] == statuses()[c] == "SENT", "3건 중 1건 실패: 2건 SENT, 1건 FAILED")
    check(q("SELECT error_message FROM career_discord_announcements WHERE post_id = %s", (b,))[0][0].startswith("전송 실패"),
          "실패 사유 기록")
    channel3.fail_ids = set()
    check(await svc3.run(day4 + timedelta(days=1)) == 1 and channel3.sent[-1][0] == b
          and q("SELECT status, attempt_count FROM career_discord_announcements WHERE post_id = %s", (b,))[0] == ("SENT", 2),
          "실패한 글은 다음 실행에서 재시도 후 SENT (시도 2회)")

    d = add_post("lab", "계속 실패", t + timedelta(days=5))
    channel3.fail_ids = {d}
    for offset in (6, 7, 8):
        await svc3.run(DAY1 + timedelta(days=offset))
    check(q("SELECT status, attempt_count FROM career_discord_announcements WHERE post_id = %s", (d,))[0] == ("FAILED", 3),
          "3회 실패 후 FAILED 유지")
    before = len(channel3.sent)
    channel3.fail_ids = set()
    check(await svc3.run(DAY1 + timedelta(days=9)) == 0 and len(channel3.sent) == before,
          "시도 한도 도달 후에는 자동 재시도하지 않음")

    # -- 게시 후 SENT 저장 실패 → PENDING 유지, 재공지 없음 ---------------------------
    e = add_post("reviews", "저장 실패", t + timedelta(days=10))
    channel4 = FakeChannel()
    svc4, repo4 = notice_service(channel4)
    repo4.mark_sent = Mock(side_effect=RuntimeError("db down"))
    check(await svc4.run(DAY1 + timedelta(days=10)) == 1 and statuses()[e] == "PENDING", "게시 후 저장 실패: PENDING 유지")
    svc5, _ = notice_service(channel4)
    check(await svc5.run(DAY1 + timedelta(days=11)) == 0 and len(channel4.sent) == 1, "PENDING 글은 다시 공지하지 않음")
    q("UPDATE career_discord_announcements SET claimed_at = claimed_at - interval '1 hour' WHERE post_id = %s", (e,))
    check(PostgresCareerNoticeRepository(new_database()).count_stuck_pending() == 1, "오래된 PENDING은 확인 필요로 집계")

    # -- 여러 Bot 프로세스 동시 실행: 같은 글 중복 선점 없음, 하루 5개 유지 -------------
    many = [add_post("reviews" if i % 2 else "lab", f"동시 {i}", t + timedelta(days=12, minutes=i)) for i in range(8)]
    day13 = (DAY1 + timedelta(days=12)).date()
    repos = [PostgresCareerNoticeRepository(new_database()) for _ in range(4)]
    with ThreadPoolExecutor(max_workers=4) as pool:
        results = list(pool.map(lambda r: r.claim_due(day13, 5, 3, ("reviews", "lab")), repos))
    claimed = [row["post_id"] for result in results for row in result]
    check(len(claimed) == 5 and len(set(claimed)) == 5 and set(claimed) == set(many[:5]),
          "4개 프로세스 동시 선점: 합계 5개, 중복 없음, 오래된 순")

    # -- 웹 주소 미설정: 선점·전송하지 않음 ------------------------------------------
    f = add_post("lab", "주소 없음", t + timedelta(days=20))
    channel5 = FakeChannel()
    svc6, _ = notice_service(channel5, base_url=None)
    check(await svc6.run(DAY1 + timedelta(days=20)) == 0 and not channel5.sent and f not in statuses(),
          "웹 주소 미설정: 잘못된 링크 없이 미전송, 이력도 남기지 않음")


asyncio.run(main())
print(f"PASS: {checks} career notice DB assertions passed.")
